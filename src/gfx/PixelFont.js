const CELL_W = 6;
const CELL_H = 8;
const PER_ROW = 16;

export function createPixelFont(scene) {
  if (scene.cache.bitmapFont.has(FONT_KEY)) return;

  const rows = Math.ceil(CHARS.length / PER_ROW);
  const tex = scene.textures.createCanvas(FONT_KEY + '-tex', PER_ROW * CELL_W, rows * CELL_H);
  const ctx = tex.getContext();
  ctx.clearRect(0, 0, tex.width, tex.height);
  ctx.fillStyle = '#ffffff';

  for (let i = 0; i < CHARS.length; i++) {
    const glyph = G[CHARS[i]] || G['?'];
    const ox = (i % PER_ROW) * CELL_W;
    const oy = Math.floor(i / PER_ROW) * CELL_H;
    for (let y = 0; y < 7; y++) {
      const line = glyph[y];
      for (let x = 0; x < 5; x++) {
        if (line[x] === '#') ctx.fillRect(ox + x, oy + y, 1, 1);
      }
    }
  }
  tex.refresh();

  const fontData = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: FONT_KEY + '-tex',
    offset: { x: 0, y: 0 },
    width: CELL_W,
    height: CELL_H,
    chars: CHARS,
    charsPerRow: PER_ROW,
    spacing: { x: 0, y: 0 }
  });
  scene.cache.bitmapFont.add(FONT_KEY, fontData);
}

/** Convenience wrapper: uppercase-only text that snaps to whole pixels. */
export function label(scene, x, y, text, size = 8, tint = 0xf0e0c0) {
  const t = scene.add.bitmapText(Math.round(x), Math.round(y), FONT_KEY, String(text).toUpperCase(), size);
  t.setTint(tint);
  return t;
}
